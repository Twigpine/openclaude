import { existsSync } from 'node:fs'
import { chmod, mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { resolveCurrentCliEntrypoint } from '../cliEntrypoint.js'
import { logForDebugging } from '../debug.js'
import { getClaudeConfigHomeDir } from '../envUtils.js'
import { getPlatform, type Platform } from '../platform.js'

type ProcessLaunch = {
  command: string
  args: string[]
  requiredEntrypoint?: string
}

export function resolveClaudeInChromeLaunches({
  isNativeBuild,
  execPath = process.execPath,
  cliEntrypoint,
}: {
  isNativeBuild: boolean
  execPath?: string
  cliEntrypoint?: string
}): {
  nativeHost: ProcessLaunch
  mcpServer: ProcessLaunch
} {
  if (isNativeBuild) {
    return {
      nativeHost: {
        command: execPath,
        args: ['--chrome-native-host'],
      },
      mcpServer: {
        command: execPath,
        args: ['--claude-in-chrome-mcp'],
      },
    }
  }

  const entrypoint = resolveCurrentCliEntrypoint({ argv1: cliEntrypoint })
  return {
    nativeHost: {
      command: execPath,
      args: [entrypoint, '--chrome-native-host'],
      requiredEntrypoint: entrypoint,
    },
    mcpServer: {
      command: execPath,
      args: [entrypoint, '--claude-in-chrome-mcp'],
      requiredEntrypoint: entrypoint,
    },
  }
}

/**
 * Create the argument-free wrapper path required by native-messaging manifests.
 */
export async function createWrapperScript(
  launch: ProcessLaunch,
  {
    platform = getPlatform(),
    chromeDir = join(getClaudeConfigHomeDir(), 'chrome'),
  }: {
    platform?: Platform
    chromeDir?: string
  } = {},
): Promise<string> {
  if (launch.requiredEntrypoint && !existsSync(launch.requiredEntrypoint)) {
    throw new Error(
      'Unable to create the Claude-in-Chrome native host wrapper because the OpenClaude CLI entrypoint is unavailable.',
    )
  }

  const wrapperPath =
    platform === 'windows'
      ? join(chromeDir, 'chrome-native-host.bat')
      : join(chromeDir, 'chrome-native-host')

  const scriptContent = renderWrapperScript(launch, platform)

  const existingContent = await readFile(wrapperPath, 'utf-8').catch(() => null)
  if (existingContent === scriptContent) {
    if (platform !== 'windows') {
      const existingMode = (await stat(wrapperPath)).mode & 0o777
      if (existingMode !== 0o755) {
        await chmod(wrapperPath, 0o755)
      }
    }
    return wrapperPath
  }

  await mkdir(chromeDir, { recursive: true })
  await writeFile(wrapperPath, scriptContent)

  if (platform !== 'windows') {
    await chmod(wrapperPath, 0o755)
  }

  logForDebugging(
    `[Claude in Chrome] Created Chrome native host wrapper script: ${wrapperPath}`,
  )
  return wrapperPath
}

function quotePosixArgument(value: string): string {
  return `'${value.replaceAll("'", `'"'"'`)}'`
}

function quoteWindowsBatchArgument(value: string): string {
  if (/[\0\r\n"]/.test(value)) {
    throw new Error(
      'Unable to create the Claude-in-Chrome native host wrapper from an invalid command argument.',
    )
  }
  return `"${value.replaceAll('%', '%%')}"`
}

export function renderWrapperScript(
  launch: Pick<ProcessLaunch, 'command' | 'args'>,
  platform: Platform,
): string {
  const quote =
    platform === 'windows' ? quoteWindowsBatchArgument : quotePosixArgument
  const command = [launch.command, ...launch.args].map(quote).join(' ')

  return platform === 'windows'
    ? `@echo off
setlocal DisableDelayedExpansion
REM Chrome native host wrapper script
REM Generated by Claude Code - do not edit manually
${command}
`
    : `#!/bin/sh
# Chrome native host wrapper script
# Generated by Claude Code - do not edit manually
exec ${command}
`
}
