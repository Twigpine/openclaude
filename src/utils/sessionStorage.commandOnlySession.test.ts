import { afterEach, beforeEach, expect, test } from 'bun:test'
import { type UUID } from 'node:crypto'
import { existsSync } from 'node:fs'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import {
  acquireSharedMutationLock,
  releaseSharedMutationLock,
} from '../test/sharedMutationLock.js'
import {
  getSessionId,
  isSessionPersistenceDisabled,
  setSessionPersistenceDisabled,
  switchSession,
} from '../bootstrap/state.js'
import type { Message } from '../types/message.js'
import { setClaudeConfigHomeDirForTesting } from './envUtils.js'
import {
  createAssistantMessage,
  createUserMessage,
  NO_RESPONSE_REQUESTED,
} from './messages.js'
import {
  flushSessionStorage,
  getTranscriptPathForSession,
  recordTranscript,
  resetProjectForTesting,
  resetSessionFilePointer,
  sessionIdExists,
} from './sessionStorage.js'

const SESSION = '00000000-0000-4000-8000-00000000c001' as UUID
const tempDirs: string[] = []
const savedEnv = {
  NODE_ENV: process.env.NODE_ENV,
  TEST_ENABLE_SESSION_PERSISTENCE: process.env.TEST_ENABLE_SESSION_PERSISTENCE,
  ENABLE_SESSION_PERSISTENCE: process.env.ENABLE_SESSION_PERSISTENCE,
}
let originalSessionId: string
let originalPersistenceDisabled: boolean

beforeEach(async () => {
  await acquireSharedMutationLock('utils/sessionStorage.commandOnlySession.test.ts')
  originalSessionId = getSessionId()
  originalPersistenceDisabled = isSessionPersistenceDisabled()
  process.env.NODE_ENV = 'development'
  process.env.TEST_ENABLE_SESSION_PERSISTENCE = 'true'
  process.env.ENABLE_SESSION_PERSISTENCE = 'true'
  setSessionPersistenceDisabled(false)
  const configDir = await mkdtemp(join(tmpdir(), 'openclaude-command-only-'))
  tempDirs.push(configDir)
  setClaudeConfigHomeDirForTesting(configDir)
  resetProjectForTesting()
  switchSession(SESSION as never)
  await resetSessionFilePointer()
})

afterEach(async () => {
  try {
    for (const [key, value] of Object.entries(savedEnv)) {
      if (value === undefined) delete process.env[key]
      else process.env[key] = value
    }
    setSessionPersistenceDisabled(originalPersistenceDisabled)
    switchSession(originalSessionId as never)
    resetProjectForTesting()
    await Promise.all(
      tempDirs.splice(0).map(dir => rm(dir, { recursive: true, force: true })),
    )
  } finally {
    releaseSharedMutationLock()
  }
})

/** What a local slash command such as `/clear` or `/exit` records. */
function localCommand(name: string, output: string): Message[] {
  return [
    createUserMessage({
      content: '<local-command-caveat>Caveat: generated by the user.</local-command-caveat>',
      isMeta: true,
    }),
    createUserMessage({
      content: `<command-name>/${name}</command-name>\n<command-message>${name}</command-message>\n<command-args></command-args>`,
    }),
    createUserMessage({
      content: `<local-command-stdout>${output}</local-command-stdout>`,
    }),
  ]
}

test('a launch that only runs local commands leaves no transcript', async () => {
  const messages = [
    ...localCommand('clear', ''),
    ...localCommand('exit', 'Catch you later!'),
    createAssistantMessage({ content: NO_RESPONSE_REQUESTED }),
  ]
  await recordTranscript(messages)
  await flushSessionStorage()

  expect(existsSync(getTranscriptPathForSession(SESSION))).toBe(false)
  // No file means no "Resume this session with" hint at exit.
  expect(sessionIdExists(SESSION)).toBe(false)
})

test('the first real prompt saves the session with the earlier commands', async () => {
  const commands = localCommand('model', 'Set model to test')
  await recordTranscript(commands)
  const prompt = createUserMessage({ content: 'explain this repo' })
  await recordTranscript([...commands, prompt])
  await flushSessionStorage()

  const transcript = getTranscriptPathForSession(SESSION)
  expect(existsSync(transcript)).toBe(true)
  const uuids = (await readFile(transcript, 'utf8'))
    .trim()
    .split('\n')
    .map(line => JSON.parse(line).uuid)
  for (const message of [...commands, prompt]) {
    expect(uuids).toContain(message.uuid)
  }
})

test('a model reply also saves the session', async () => {
  const reply = createAssistantMessage({ content: 'hello' })
  reply.message.model = 'test-model'
  await recordTranscript([...localCommand('clear', ''), reply])
  await flushSessionStorage()

  expect(existsSync(getTranscriptPathForSession(SESSION))).toBe(true)
})
