#!/usr/bin/env bun
/**
 * emit-cli-dev.ts — Write ./cli-dev thin Node launcher → bin/openclaude → dist/cli.mjs
 * Free-Code Port Step-1 (OC-native path). NOT FC bun --compile.
 */
import { chmodSync, existsSync, writeFileSync } from 'fs'
import { resolve } from 'path'

const root = resolve(import.meta.dir, '..')
const dist = resolve(root, 'dist/cli.mjs')
const bin = resolve(root, 'bin/openclaude')
const out = resolve(root, 'cli-dev')
const stamp = resolve(root, 'cli-dev.stamp.json')

if (!existsSync(dist)) {
  console.error('emit-cli-dev: missing dist/cli.mjs — run bun run scripts/build.ts first')
  process.exit(1)
}
if (!existsSync(bin)) {
  console.error('emit-cli-dev: missing bin/openclaude')
  process.exit(1)
}

const wrapper = `#!/usr/bin/env node
// Generated by scripts/emit-cli-dev.ts — OpenClaude experimental cli-dev entry
import { spawn } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const launcher = join(here, 'bin', 'openclaude')
const child = spawn(process.execPath, [launcher, ...process.argv.slice(2)], {
  stdio: 'inherit',
  env: {
    ...process.env,
    CLAUDE_CODE_EXPERIMENTAL_BUILD: process.env.CLAUDE_CODE_EXPERIMENTAL_BUILD ?? 'true',
  },
})
child.on('exit', (code, signal) => {
  if (signal) process.kill(process.pid, signal)
  process.exit(code ?? 1)
})
`

writeFileSync(out, wrapper, 'utf8')
chmodSync(out, 0o755)
const meta = {
  emitted_at: new Date().toISOString(),
  mechanism: 'oc-native-preprocess',
  points_to: 'bin/openclaude -> dist/cli.mjs',
  experimental: true,
}
writeFileSync(stamp, JSON.stringify(meta, null, 2) + '\n')
console.log(`emit-cli-dev: wrote ${out}`)
console.log(`emit-cli-dev: stamp ${stamp}`)
